// Writes src/build-info.ts so /health can report the exact source commit.
// Runs from wrangler's `build.command`, so it executes on every `wrangler deploy`
// regardless of how the deploy was started (Workers Builds, CLI, dry-run).
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
let commit = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || "";
let dirty = false;
if (!commit) {
  try {
    commit = execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
    dirty = execSync("git status --porcelain -- .", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim() !== "";
  } catch { commit = "unknown"; }
}
const target = new URL("../src/build-info.ts", import.meta.url);
let info = { version: pkg.version, commit, dirty, builtAt: new Date().toISOString() };
// Idempotent: keep the existing file (and its timestamp) when nothing but the timestamp would change, so file watchers
// (wrangler dev) do not restart in a loop. The authoritative deploy time is /health.deployment.timestamp.
if (existsSync(target)) {
  const m = /BUILD = (\{.*\}) as const/.exec(readFileSync(target, "utf8"));
  try { const old = m && JSON.parse(m[1]); if (old && old.version === info.version && old.commit === info.commit && old.dirty === info.dirty) info = old; } catch { /* regenerate */ }
}
const body = `// GENERATED by scripts/build-info.mjs; do not edit or commit.\nexport const BUILD = ${JSON.stringify(info)} as const;\n`;
if (!existsSync(target) || readFileSync(target, "utf8") !== body) writeFileSync(target, body);
console.log("build-info:", JSON.stringify(info));
